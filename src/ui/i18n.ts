const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, de };

export type Translate = (
  key: MessageKey | string,
  vars?: Record<string, string>
) => string;

/** Unknown keys (a host's custom type or stage) fall back to the raw value. */
export function translator(
  locale: Locale,
  overrides: Partial<Record<string, string>> = {}
): Translate {
  const dict = dictionaries[locale];
  return (key, vars) => {
    const raw =
      overrides[key] ??
      (dict as Record<string, string>)[key] ??
      key.split('.').at(-1) ??
      key;
    return vars
      ? raw.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '')
      : raw;
  };
}

export function toLocale(value: string | null | undefined): Locale {
  return value?.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function relativeTime(date: string | Date, locale: Locale) {
  const minutes = Math.round((Date.now() - new Date(date).getTime()) / 60_000);
  const format = new Intl.RelativeTimeFormat(locale, { numeric: 'auto' });
  if (minutes < 60) return format.format(-minutes, 'minute');
  const hours = Math.round(minutes / 60);
  if (hours < 48) return format.format(-hours, 'hour');
  return format.format(-Math.round(hours / 24), 'day');
}

/** The first weekday after `date`, when a reply can be expected again. */
export function nextWorkday(date: Date) {
  const next = new Date(date);
  do next.setDate(next.getDate() + 1);
  while (next.getDay() === 0 || next.getDay() === 6);
  return next;
}

export function duration(since: string | Date, locale: Locale) {
  const minutes = Math.max(
    0,
    Math.round((Date.now() - new Date(since).getTime()) / 60_000)
  );
  const [value, unit] =
    minutes < 60
      ? [minutes, 'minute']
      : minutes < 48 * 60
        ? [Math.round(minutes / 60), 'hour']
        : [Math.round(minutes / 1440), 'day'];
  return new Intl.NumberFormat(locale, {
    style: 'unit',
    unit,
    unitDisplay: 'short',
  }).format(value);
}
